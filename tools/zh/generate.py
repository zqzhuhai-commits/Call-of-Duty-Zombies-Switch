#!/usr/bin/env python3
"""Generate a small Chinese atlas and deterministic C catalog. Requires Pillow."""
from pathlib import Path
import argparse,json,re,math
from PIL import Image,ImageDraw,ImageFont
root=Path(__file__).resolve().parents[2]
p=argparse.ArgumentParser();p.add_argument('--font',required=True);a=p.parse_args()
entries={}
for n,line in enumerate((root/'localization/zh_CN.tsv').read_text().splitlines(),1):
    if not line or line.startswith('#'): continue
    en,zh=line.split('\t',1)
    if en in entries: raise ValueError(f'duplicate entry: {n}: {en}')
    entries[en]=zh
text=''.join(entries.values())+(root/'engine/source/menu/menu_loadscreen_tips.h').read_text()
cps=sorted({ord(c) for c in text if ord(c)>255})
cols=28;cell=36;height=1
while height<math.ceil(len(cps)/cols)*cell: height*=2
width=1
while width<cols*cell: width*=2
im=Image.new('RGBA',(width,height),(255,255,255,0));d=ImageDraw.Draw(im)
f=ImageFont.truetype(a.font,34)
f.set_variation_by_axes([550])
for i,cp in enumerate(cps):
    x=(i%cols)*cell;y=(i//cols)*cell
    d.text((x+cell/2,y+cell/2),chr(cp),font=f,fill=(255,255,255,255),anchor='mm')
out=root/'overlay/romfs/nzp/gfx';out.mkdir(parents=True,exist_ok=True)
import io,gzip,base64
buf=io.BytesIO(); im.save(buf,format='TGA')
(out/'charset_zh.tga.gz.b64').write_text(base64.b64encode(gzip.compress(buf.getvalue(),mtime=0)).decode()+'\n')
c=lambda s:json.dumps(s,ensure_ascii=False)
header='/* Generated by tools/zh/generate.py. Do not edit. */\n#pragma once\n'
header+=f'#define ZH_GLYPH_COUNT {len(cps)}\n#define ZH_GLYPH_ADVANCE 12\n#define ZH_GLYPH_CELL {cell}\n#define ZH_ATLAS_COLUMNS {cols}\n#define ZH_ATLAS_WIDTH {width}\n#define ZH_ATLAS_HEIGHT {height}\n'
header+='static const unsigned int zh_codepoints[] = {'+','.join(map(str,cps))+'};\n'
header+='static const struct { const char *en; const char *zh; } zh_catalog[] = {\n'
header+=''.join('{'+c(en)+','+c(zh)+'},\n' for en,zh in sorted(entries.items()))+'};\n'
(root/'overlay/source/zh_catalog.h').write_text(header)
print(f'{len(entries)} translations; {len(cps)} glyphs; atlas {width}x{height}')
